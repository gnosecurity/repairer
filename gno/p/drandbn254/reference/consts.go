package main

import (
	"fmt"

	"github.com/consensys/gnark-crypto/ecc/bn254/fp"
)

// printConsts prints the SvdW constants as plain integers, for the gno port.
func printConsts() {
	for name, e := range map[string]fp.Element{
		"Z":  {15230403791020821917, 754611498739239741, 7381016538464732716, 1011752739694698287},
		"c1": {1248766071674976557, 10548065924188627562, 16242874202584236114, 560012691975822483},
		"c2": {12997850613838968789, 14304628359724097447, 2950087706404981016, 1237622763554136189},
		"c3": {8972444824031832946, 5898165201680709844, 10690697896010808308, 824354360198587078},
		"c4": {12077013577332951089, 1872782865047492001, 13514471836495169457, 415649166299893576},
	} {
		fmt.Printf("%s = %s\n", name, e.String())
	}
}
